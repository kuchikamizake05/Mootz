import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { keccak256 } from 'viem';
for (const name of ['MeetRegistry', 'EventCollection']) {
  const artifact = JSON.parse(readFileSync(new URL(`../out/${name}.sol/${name}.json`, import.meta.url)));
  const output = JSON.stringify(artifact.abi, null, 2) + '\n';
  const path = fileURLToPath(new URL(`../abi/${name}.json`, import.meta.url));
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== output) throw new Error(`Stale ABI: ${name}`);
  } else { writeFileSync(path, output); }
  console.log(`${name}: ABI ${process.argv.includes('--check') ? 'matches' : 'exported'}, creation bytecode hash ${keccak256(artifact.bytecode.object)}`);
}

const protocol = await import('../specs/typed-data.mjs');
const types = { ...protocol.meetTypes, ...protocol.claimTypes };
const typeName = (field) => field === 'address' ? 'Address' : field.startsWith('uint') ? 'bigint' : 'Hex';
const typedOutput = '// Generated by npm run export. Edit typed-data.mjs, not this file.\n' +
  'import type { Address, Hex } from "viem";\n\n' +
  `export const meetTypes = ${JSON.stringify(protocol.meetTypes, null, 2)} as const;\n` +
  `export const claimTypes = ${JSON.stringify(protocol.claimTypes, null, 2)} as const;\n` +
  `export const RECORD_MEET = "${protocol.RECORD_MEET}" as const;\n` +
  `export const OFFCHAIN_MEET = "${protocol.OFFCHAIN_MEET}" as const;\n\n` +
  Object.entries(types).map(([name, fields]) => `export type ${name} = {\n${fields.map((f) => `  ${f.name}: ${typeName(f.type)};`).join('\n')}\n};\n`).join('\n');
const typePath = fileURLToPath(new URL('../specs/protocol.ts', import.meta.url));
if (process.argv.includes('--check')) {
  if (readFileSync(typePath, 'utf8') !== typedOutput) throw new Error('Stale protocol types');
} else { writeFileSync(typePath, typedOutput); }
