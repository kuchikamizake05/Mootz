// Generates TypeScript types from the backend OpenAPI specs in be/specs/.
// Usage: node scripts/gen-api.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const specs = new URL('../../../be/specs/', import.meta.url);
const target = new URL('../src/lib/api/generated/', import.meta.url);
const check = process.argv.includes('--check');
const header = '// Generated by npm run gen:api from be/specs. Do not edit.\n';

mkdirSync(target, { recursive: true });
const drift = [];
const names = readdirSync(specs).filter((name) => name.endsWith('.openapi.json')).sort();

for (const name of names) {
  const schema = JSON.parse(readFileSync(new URL(name, specs), 'utf8'));
  const output = header + astToString(await openapiTS(schema));
  const dest = new URL(name.replace('.openapi.json', '.ts'), target);
  let current = null;
  try {
    current = readFileSync(dest, 'utf8');
  } catch {}
  if (current === output) continue;
  if (check) drift.push(name);
  else writeFileSync(dest, output);
}

if (drift.length) {
  console.error(`API type drift (${drift.join(', ')}): run npm run gen:api from fe/web`);
  process.exit(1);
}
console.log(check ? 'API types match be/specs.' : `Generated ${names.length} API type files.`);
